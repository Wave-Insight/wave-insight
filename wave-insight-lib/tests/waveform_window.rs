//! The bounded window streaming API for drawing: one pass, fair per-signal cap,
//! left-edge value where the cache can provide it, and no full-history decode.

use wave_insight_lib::waveform::{Change, Waveform, WaveformError};

/// A valid VCD with a dense clock, a sparse bus and an idle bit.
///
/// dense toggles happen at times 1..=dense (plus the initial #0 frame), the bus
/// changes every 10 toggles and the idle bit changes once at #0.
fn dense_vcd(dense: usize) -> String {
    let mut vcd = String::with_capacity(dense * 12 + 512);
    vcd.push_str("$date generated by waveform_window test $end\n$version 1 $end\n");
    vcd.push_str("$timescale 1ns $end\n$scope module top $end\n");
    vcd.push_str("$var wire 1 ! clk $end\n");
    vcd.push_str("$var wire 8 % data [7:0] $end\n");
    vcd.push_str("$var wire 1 & idle $end\n");
    vcd.push_str("$upscope $end\n$enddefinitions $end\n#0\n0!\nb00000000 %\n0&\n");
    for step in 1..=dense {
        vcd.push_str(&format!("#{step}\n"));
        vcd.push(if step % 2 == 0 { '0' } else { '1' });
        vcd.push_str("!\n");
        if step % 10 == 0 {
            vcd.push_str(&format!("b{:08b} %\n", (step / 10) as u8));
        }
    }
    vcd
}

fn open_dense(dense: usize) -> (Waveform, usize, usize, usize) {
    let waveform = Waveform::open_bytes(dense_vcd(dense).into_bytes()).expect("dense VCD opens");
    let clock = waveform.signal_by_path("top.clk").expect("clk").index();
    let data = waveform.signal_by_path("top.data").expect("data").index();
    let idle = waveform.signal_by_path("top.idle").expect("idle").index();
    (waveform, clock, data, idle)
}

fn decoded_window(waveform: &Waveform, signal: usize, start: u64, end: Option<u64>) -> Vec<Change> {
    waveform
        .decoded_changes(signal)
        .expect("decoded")
        .window(start, end)
        .to_vec()
}

#[test]
fn window_matches_the_decoded_window_and_returns_the_left_edge_value() {
    let (waveform, clock, data, idle) = open_dense(500);
    let indices = [clock, data, idle];
    let expected: Vec<Vec<Change>> = indices
        .iter()
        .map(|signal| decoded_window(&waveform, *signal, 100, Some(300)))
        .collect();
    let rows = waveform
        .window_changes_many(&indices, 100, Some(300), 10_000)
        .expect("window query");
    assert_eq!(rows.len(), 3);
    for (row, expected) in rows.iter().zip(&expected) {
        assert_eq!(
            &row.changes, expected,
            "changes must match decoded_changes.window"
        );
        assert!(!row.capped, "ten thousand changes cannot cap these rows");
    }
    // The cache is warm (decoded above), so the left edge value is available
    // for rows whose first in-window change is after the window start.
    for (row, signal) in rows.iter().zip(indices) {
        let decoded = waveform.decoded_changes(signal).expect("decoded");
        if row
            .changes
            .first()
            .map(|change| change.0 > 100)
            .unwrap_or(true)
        {
            let expected = decoded.value_at(100).cloned();
            assert_eq!(row.before, expected, "left edge value for signal {signal}");
        }
    }
}

#[test]
fn cold_window_does_not_materialise_the_body_for_the_left_edge() {
    let (waveform, clock, data, idle) = open_dense(500);
    let indices = [clock, data, idle];
    let rows = waveform
        .window_changes_many(&indices, 100, Some(300), 10_000)
        .expect("window query");
    assert_eq!(rows.len(), 3);
    assert!(!rows[0].changes.is_empty() && !rows[1].changes.is_empty());
    for row in &rows {
        assert_eq!(
            row.before, None,
            "a cold cache cannot provide the left edge"
        );
    }
    // Streaming must not materialise the parsed body (that would be the full
    // history in memory), so the cache stats are still empty.
    assert_eq!(waveform.cache_stats(), Default::default());
}

#[test]
fn per_signal_cap_is_fair_and_bounded() {
    let (waveform, clock, data, idle) = open_dense(500);
    let rows = waveform
        .window_changes_many(&[clock, data, idle], 0, None, 5)
        .expect("window query");
    assert_eq!(rows[0].changes.len(), 5, "the dense clock stops at the cap");
    assert!(rows[0].capped);
    assert_eq!(
        rows[1].changes.len(),
        5,
        "the sparse-ish bus also gets five slots"
    );
    assert!(rows[1].capped);
    assert_eq!(rows[2].changes.len(), 1, "the idle bit has only one change");
    assert!(!rows[2].capped);
    // The cap is per signal: far below the ~550 changes in the window.
    assert!(rows.iter().map(|row| row.changes.len()).sum::<usize>() <= 5 * 3);
    let dense_changes = decoded_window(&waveform, clock, 0, None).len();
    assert!(
        dense_changes > 5 * 3,
        "the fixture must be dense: {dense_changes}"
    );
}

#[test]
fn zoomed_window_caps_only_what_needs_capping() {
    let (waveform, clock, data, _idle) = open_dense(500);
    let rows = waveform
        .window_changes_many(&[clock, data], 200, Some(210), 4)
        .expect("zoom window");
    assert_eq!(rows[0].changes.len(), 4);
    assert!(rows[0].capped);
    assert!(!rows[1].changes.is_empty());
    assert!(!rows[1].capped, "the bus changes once per ten steps");
}

#[test]
fn empty_window_zero_cap_unknown_and_duplicate_requests() {
    let (waveform, clock, data, _idle) = open_dense(100);

    // start > end: empty lists, no error and no capped flags.
    let rows = waveform
        .window_changes_many(&[clock, data], 10, Some(5), 7)
        .expect("empty window");
    assert!(rows.iter().all(|row| row.changes.is_empty() && !row.capped));

    // a cap of zero collects nothing and reports capped.
    let rows = waveform
        .window_changes_many(&[clock], 0, None, 0)
        .expect("zero cap");
    assert!(rows[0].changes.is_empty());
    assert!(rows[0].capped);

    // unknown indices are errors, not panics.
    let error = waveform
        .window_changes_many(&[usize::MAX], 0, None, 10)
        .expect_err("unknown signal");
    assert!(
        matches!(error, WaveformError::UnknownSignal(_)),
        "{error:?}"
    );

    // duplicates collapse and keep the first occurrence order.
    let rows = waveform
        .window_changes_many(&[data, clock, data], 0, Some(20), 100)
        .expect("duplicates");
    assert_eq!(rows.len(), 2);
    assert_eq!(
        rows[0].changes,
        decoded_window(&waveform, data, 0, Some(20))
    );
    assert_eq!(
        rows[1].changes,
        decoded_window(&waveform, clock, 0, Some(20))
    );

    // no signals requested: an empty answer without touching the file.
    assert!(waveform
        .window_changes_many(&[], 0, None, 10)
        .expect("no signals")
        .is_empty());
}

#[test]
fn window_after_the_last_change_returns_the_final_value_as_before() {
    let (waveform, clock, _data, _idle) = open_dense(50);
    let last = decoded_window(&waveform, clock, 0, None);
    let after = last.last().expect("clock changes").0;
    let rows = waveform
        .window_changes_many(&[clock], after + 100, Some(after + 200), 10)
        .expect("window after end");
    assert!(rows[0].changes.is_empty());
    assert!(!rows[0].capped);
    assert_eq!(rows[0].before, last.last().map(|(_, value)| value.clone()));
}

#[test]
fn aliased_variables_report_their_own_window() {
    let vcd = "$timescale 1ns $end\n$scope module top $end\n\
               $var wire 8 ! data [7:0] $end\n\
               $var wire 8 ! alias [7:0] $end\n\
               $upscope $end\n$enddefinitions $end\n#0\nb00000000 !\n#10\nb10101010 !\n#20\nb11110000 !\n";
    let waveform = Waveform::open_bytes(vcd.as_bytes().to_vec()).expect("alias VCD opens");
    let data = waveform.signal_by_path("top.data").expect("data").index();
    let alias = waveform.signal_by_path("top.alias").expect("alias").index();
    let rows = waveform
        .window_changes_many(&[data, alias], 5, Some(25), 10)
        .expect("alias window");
    assert_eq!(rows[0].changes, rows[1].changes);
    assert_eq!(
        rows[0].changes,
        decoded_window(&waveform, data, 5, Some(25))
    );
    assert_eq!(rows[0].changes.len(), 2);
}

#[test]
fn fst_fixture_window_matches_the_decoded_window() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/data/io_mode_wave.fst");
    let waveform = Waveform::open_path(path).expect("FST fixture opens");
    let indices: Vec<usize> = waveform
        .signals()
        .iter()
        .take(3)
        .map(|signal| signal.index())
        .collect();
    let hint = waveform
        .time_range_hint()
        .expect("time hint")
        .expect("non-empty fixture");
    let start = hint.start + (hint.end.saturating_sub(hint.start)) / 3;
    let end = hint.start + (hint.end.saturating_sub(hint.start)) * 2 / 3;
    let expected: Vec<Vec<Change>> = indices
        .iter()
        .map(|signal| decoded_window(&waveform, *signal, start, Some(end)))
        .collect();
    let rows = waveform
        .window_changes_many(&indices, start, Some(end), 512)
        .expect("FST window query");
    for (row, expected) in rows.iter().zip(expected) {
        assert_eq!(row.changes, expected);
    }
}

#[test]
fn randomly_sampled_windows_match_decoded_changes() {
    let (waveform, clock, data, idle) = open_dense(300);
    let indices = [clock, data, idle];
    let end_time = 300u64;
    let mut state = 0x5eed_u64;
    for _ in 0..12 {
        state = state
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        let start = state % (end_time + 1);
        state = state
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        let end = start + state % (end_time - start + 1);
        let rows = waveform
            .window_changes_many(&indices, start, Some(end), 10_000)
            .expect("random window");
        for (row, signal) in rows.iter().zip(indices) {
            assert_eq!(
                row.changes,
                decoded_window(&waveform, signal, start, Some(end)),
                "window {start}..={end}, signal {signal}"
            );
        }
    }
}
